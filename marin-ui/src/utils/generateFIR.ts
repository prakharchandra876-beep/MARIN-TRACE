import jsPDF from 'jspdf';
import autoTable from 'jspdf-autotable';

export const generateFIR = (vesselData: any) => {
  const doc = new jsPDF();
  const timestamp = new Date().toISOString();

  // Header
  doc.setFont("helvetica", "bold");
  doc.setFontSize(18);
  doc.setTextColor(220, 38, 38); // Red title
  doc.text("OFFICIAL FIRST INFORMATION REPORT (FIR)", 14, 20);
  
  doc.setFontSize(10);
  doc.setTextColor(100, 100, 100);
  doc.text("SMART INDIA HACKATHON 2026 | ISRO MARITIME DOMAIN AWARENESS", 14, 28);
  doc.text(`Generated by MARIN-TRACE Platform | Timestamp: ${timestamp}`, 14, 34);

  // Line break
  doc.setLineWidth(0.5);
  doc.line(14, 40, 196, 40);

  // Incident Details
  doc.setFontSize(12);
  doc.setTextColor(0, 0, 0);
  doc.text("1. SUBJECT IDENTIFICATION", 14, 50);
  
  autoTable(doc, {
    startY: 55,
    theme: 'grid',
    headStyles: { fillColor: [40, 40, 40] },
    body: [
      ['MMSI Number', vesselData.mmsi || 'UNKNOWN'],
      ['Vessel Name', vesselData.name || 'UNIDENTIFIED VESSEL'],
      ['Flag State', vesselData.flag || 'UNKNOWN'],
      ['Vessel Type', vesselData.type || 'Cargo/Tanker'],
    ],
  });

  // Telemetry Snapshot
  doc.text("2. LIVE TELEMETRY SNAPSHOT", 14, (doc as any).lastAutoTable.finalY + 15);
  
  autoTable(doc, {
    startY: (doc as any).lastAutoTable.finalY + 20,
    theme: 'grid',
    headStyles: { fillColor: [40, 40, 40] },
    body: [
      ['Latitude', `${vesselData.lat}° N`],
      ['Longitude', `${vesselData.lng}° E`],
      ['Speed', `${vesselData.speed_knots || vesselData.speed || '0.0'} knots`],
      ['Heading', `${vesselData.heading || '0'}°`],
    ],
  });

  // Legal Violation
  const finalY = (doc as any).lastAutoTable.finalY + 15;
  doc.text("3. VIOLATION SUMMARY", 14, finalY);
  doc.setFont("helvetica", "normal");
  doc.setFontSize(10);
  doc.text(
    "Based on SAR (Synthetic Aperture Radar) and live AIS satellite telemetry cross-referencing, " +
    "the above vessel is flagged for highly suspicious behavior consistent with illegal oil dumping " +
    "or unauthorized dark vessel operations. Immediate interception is recommended.",
    14, finalY + 8, { maxWidth: 180 }
  );

  // Signature Block
  doc.text("___________________________________", 14, finalY + 40);
  doc.text("System Administrator Signature", 14, finalY + 45);

  // Save the PDF
  doc.save(`MARIN_TRACE_FIR_${vesselData.mmsi}.pdf`);
};